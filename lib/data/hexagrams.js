export const HEXAGRAMS_BY_KEY = {};
export const HEXAGRAMS_BY_NUMBER = {};

for (const row of RAW_HEXAGRAMS) {
  const [upper, lower, number, name, fullName, judgment, image] = row;
  const entry = {
    upper,
    lower,
    number,
    name,
    fullName,
    symbol: String.fromCodePoint(0x4dc0 + number - 1),
    judgment,
    image,
  };
  HEXAGRAMS_BY_KEY[`${upper}-${lower}`] = entry;
  HEXAGRAMS_BY_NUMBER[number] = entry;
}

export function lookupHexagram(upperNum, lowerNum) {
  return HEXAGRAMS_BY_KEY[`${upperNum}-${lowerNum}`];
}
