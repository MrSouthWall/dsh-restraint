function getCalendarChoices(t) {
  return ['solar', 'lunar'].map(value => ({ value, label: t(`form.${value}`) }));
}

function getGenderChoices(t, first = 'male') {
  return [first, first === 'male' ? 'female' : 'male']
    .map(value => ({ value, label: t(`form.${value}`) }));
}

function getLongitudeChoices(t) {
  return CITY_LONGITUDES.map(city => ({
    value: city.value,
    label: city.value === '' ? t('form.longitudeOff') : city.label,
  }));
}

