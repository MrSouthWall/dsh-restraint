import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const { metafile } = await build({
  absWorkingDir: root,
  entryPoints: ['src/host/chart-libraries.js'],
  outfile: 'lib/vendor/chart-libraries.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  charset: 'utf8',
  minify: true,
  metafile: true,
  banner: { js: '// Generated by scripts/build-vendor.mjs. See LICENSES.txt for third-party notices.' },
});

// Collect the licenses of the packages actually included, including transitive dependencies.
const packageDirs = new Set();
for (const input of Object.keys(metafile.inputs)) {
  const match = input.match(/^.*node_modules\/((?:@[^/]+\/)?[^/]+)/);
  if (match) packageDirs.add(resolve(root, match[0]));
}
const notices = Array.from(packageDirs, dir => {
  const { name, version } = JSON.parse(readFileSync(resolve(dir, 'package.json'), 'utf8'));
  const license = readFileSync(resolve(dir, 'LICENSE'), 'utf8').trim();
  return `${name} ${version}\n\n${license}`;
});
writeFileSync(resolve(root, 'lib/vendor/LICENSES.txt'), notices.sort().join('\n\n') + '\n');
